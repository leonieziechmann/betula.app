//! Texts of the module catalog: its list and its filter panel (`pages/catalog.rs`). The list of
//! marked modules is a list like the catalog's and shares its heads, keys and tags.

pub struct Texts {
    // ---- the page ----
    /// The title of the unfiltered catalog.
    pub title_all: &'static str,
    /// „Module · Informatik B.Sc.": the catalog of a program; the values are the program's name
    /// and its degree.
    pub title_program: fn(&str, &str) -> String,
    /// The title when the list could not be loaded.
    pub title_failed: &'static str,
    /// „…, Seite 3": the server's page of a page of the list past the first.
    pub title_page: fn(&str, u64) -> String,
    /// What search engines read of the unfiltered list: its title, on a page past the first …
    pub seo_title: &'static str,
    pub seo_title_page: fn(u64) -> String,
    /// … and its description; past the first page „Seite 3 von 40 des Modulkatalogs. " before it.
    pub seo_description: &'static str,
    pub seo_description_page: fn(u64, u64, &str) -> String,
    pub resize_filters: &'static str,
    /// The preview of a module the snapshot does not know.
    pub module_not_found: &'static str,
    pub module_not_in_catalog: &'static str,
    pub close_preview: &'static str,

    // ---- „Passt in meinen Stundenplan" ----
    /// „keine Termine im WiSe 2026/27": at a module that could not be checked; the value is the
    /// semester.
    pub fit_undated: fn(&str) -> String,
    /// „SoSe 2027: noch keine Termine veröffentlicht.": above a list nothing of which could be
    /// checked.
    pub fit_unpublished: fn(&str) -> String,
    /// „Kein Modul passt in deinen Stundenplan für WiSe 2026/27": the empty list's heading.
    pub nothing_fits: fn(&str) -> String,
    /// What to leave out of the comparison when nothing fits.
    pub advice_exercises_or_exams: &'static str,
    pub advice_exercises: &'static str,
    pub advice_exams: &'static str,
    pub advice_lectures: &'static str,
    /// What to do when a list is empty: „Nimm Filter zurück oder suche nach einem anderen Begriff."
    pub advice_filters: &'static str,

    // ---- the tags of the active filters: „<group> <value>" ----
    pub tag_search: &'static str,
    pub tag_semester: &'static str,
    /// „Art": the kind of a module in the program (Pflicht, Wahlpflicht …).
    pub tag_kind: &'static str,
    /// „Passt in WiSe 2026/27".
    pub tag_fits: &'static str,
    pub tag_grading: &'static str,
    pub tag_places: &'static str,
    pub tag_status: &'static str,
    pub tag_bookmarks: &'static str,
    /// „bei Meer", „nicht bei Köhler": the value is the person.
    pub tag_lecturer: &'static str,
    pub tag_not_lecturer: &'static str,
    /// A value left out: „ohne Vorlesung", and one that is not: „nicht Englisch".
    pub without_value: fn(&str) -> String,
    pub not_value: fn(&str) -> String,
    /// „ohne Angabe": the semester of a module the plan places in none.
    pub unstated: &'static str,
    /// An area the snapshot has no name for: „Bereich 12".
    pub area_numbered: fn(i64) -> String,
    pub scheduled: &'static str,
    pub unscheduled: &'static str,
    pub winter: &'static str,
    pub summer: &'static str,
    pub irregular: &'static str,
    pub not_winter: &'static str,
    pub not_summer: &'static str,
    pub not_irregular: &'static str,
    /// „ab 6", „bis 12": credits, the number written already; the unit follows where it is said.
    pub credits_from: fn(&str) -> String,
    pub credits_up_to: fn(&str) -> String,
    pub graded: &'static str,
    pub ungraded: &'static str,
    pub limited: &'static str,
    pub unlimited: &'static str,
    pub fues_only: &'static str,
    pub fues_without: &'static str,
    /// „1 Semester", „2 Semester": how long a module lasts.
    pub semesters: fn(u8) -> String,
    pub not_offered_too: &'static str,
    pub saved_only: &'static str,
    pub saved_without: &'static str,

    // ---- the list ----
    /// What the number above the list counts: the FÜS list of a program, its curriculum, or
    /// modules.
    pub count_fues: &'static str,
    pub count_curriculum: &'static str,
    pub count_one: &'static str,
    pub count_many: &'static str,
    pub unknown_program_title: &'static str,
    pub unknown_program_hint: &'static str,
    /// The server's page with the finder on: it cannot know the plan.
    pub fits_server_title: &'static str,
    pub fits_server_hint: &'static str,
    pub without_filter: &'static str,
    /// „Gemerkt" on, and nothing marked is left.
    pub saved_none_title: &'static str,
    pub saved_none_hint: &'static str,
    pub to_bookmarks: &'static str,
    /// The server's page with „Gemerkt" on: it cannot know the marks.
    pub saved_server_title: &'static str,
    pub saved_server_hint: &'static str,
    pub show_all: &'static str,
    pub none_found_title: &'static str,
    pub reset_all: &'static str,
    /// The heads of the columns („Spr." is the language, short).
    pub col_module: &'static str,
    pub col_responsible: &'static str,
    pub col_language: &'static str,
    /// „Termine": a column, a group of the filter and a tag.
    pub dates: &'static str,
    /// „Turnus": when a module is offered; a column and a tag.
    pub turnus: &'static str,
    /// „Prüfung": a column, a group of the filter and a tag.
    pub exam: &'static str,
    /// The keys of a list as its head says them: the tooltip, and each word after its key („↑↓
    /// wählen, Enter öffnen, M merken").
    pub keys_title: &'static str,
    pub key_move: &'static str,
    pub key_open: &'static str,
    pub key_save: &'static str,
    /// The filter panel's name, its heading and the button that opens it on a phone.
    pub filters: &'static str,
    pub program_page: &'static str,
    pub remove_filter: &'static str,
    /// The end of a list longer than a page: „Ende der Liste · 1.204 Module"; the number is
    /// written already.
    pub list_end: fn(&str) -> String,
    /// The pager of the server's list: its name, „Seite 2 von 40", the link forward.
    pub pages: &'static str,
    pub page_of: fn(u64, u64) -> String,
    pub next: &'static str,

    // ---- what the plan asks for in a semester, above the list ----
    /// „Der Regelstudienplan sieht im 3. Semester außerdem vor:".
    pub plan_lead: fn(u8) -> String,
    /// An area's name as a link: „„Mathematik“".
    pub quoted: fn(&str) -> String,
    /// Before the last of several areas: „„Mathematik“, „Chemie“ oder „Physik“".
    pub or: &'static str,
    /// „Seminar X: unter diesem Namen nicht im Katalog"; the value is the name in the plan.
    pub plan_not_in_catalog: fn(&str) -> String,
    /// „Fachübergreifendes Studium: siehe FÜS-Liste".
    pub plan_fues: &'static str,
    pub fues_list: &'static str,
    /// „Wahlpflicht: alle Wahlpflichtmodule"; the value is the name in the plan.
    pub plan_all_electives: fn(&str) -> String,
    pub plan_from_areas: &'static str,
    pub plan_from_area: &'static str,
    pub plan_derived: &'static str,

    // ---- a row ----
    /// The turnus at a row, where it has to be short.
    pub row_winter: &'static str,
    pub row_summer: &'static str,
    pub row_every: &'static str,
    pub row_irregular: &'static str,
    /// „k. A." (keine Angabe): what the row does not know.
    pub row_unknown: &'static str,
    /// „noch keine Termine", „1 Termin", „12 Termine": the dates of the module's newest semester.
    pub events: fn(i64) -> String,
    /// The same in the column, where there are none.
    pub events_none: &'static str,
    pub limited_places: &'static str,

    // ---- the filter panel ----
    /// The heading of „Mein Studiengang" at the top of the program picker.
    pub my_program: &'static str,
    /// The program picker: what it picks, its button while nothing is picked, its search.
    pub program: &'static str,
    pub all_programs: &'static str,
    pub search_program: &'static str,
    pub no_plan: &'static str,
    /// „Alle": the choice of a row that leaves the value open.
    pub all: &'static str,
    /// The tooltip of „?", the semesters of the plan's modules it places in none.
    pub unplaced: &'static str,
    pub plan_semesters: &'static str,
    pub plan_semester: &'static str,
    /// „5 Bereiche": the area picker's button with several areas chosen.
    pub areas_count: fn(usize) -> String,
    pub area: &'static str,
    pub all_areas: &'static str,
    pub search_area: &'static str,
    /// The program's lists: its curriculum or its FÜS list.
    pub list: &'static str,
    pub curriculum: &'static str,
    pub module_kind: &'static str,
    pub not_stated: &'static str,
    /// A chosen person: modules with them, without them; the words are those of the legend.
    pub with_person: &'static str,
    pub without_person: &'static str,
    pub with: &'static str,
    pub without: &'static str,
    pub remove: &'static str,
    /// „Meer entfernen"; the value is the person.
    pub remove_person: fn(&str) -> String,
    pub lecturers: &'static str,
    pub add_person: &'static str,
    pub search_name: &'static str,
    /// The field for a person on the server's page, which has no picker.
    pub teaches: &'static str,
    pub name_placeholder: &'static str,
    pub department: &'static str,
    pub all_departments: &'static str,
    pub search_department: &'static str,
    /// „Passt in meinen Stundenplan", and the classes it compares.
    pub fits: &'static str,
    pub fits_held: &'static str,
    pub lectures: &'static str,
    pub exercises: &'static str,
    pub exercises_title: &'static str,
    pub exams: &'static str,
    pub undated: &'static str,
    pub undated_title: &'static str,
    pub close_filters: &'static str,
    pub confirmed: &'static str,
    pub offered_in: &'static str,
    pub winter_chip: &'static str,
    pub summer_chip: &'static str,
    pub irregular_chip: &'static str,
    pub teaching_form: &'static str,
    pub language: &'static str,
    pub properties: &'static str,
    pub graded_chip: &'static str,
    pub limited_chip: &'static str,
    pub saved_chip: &'static str,
    pub more_filters: &'static str,
    /// Under the chosen persons: what „+" and „×" mean.
    pub people_any: &'static str,
    pub people_none: &'static str,
    pub duration: &'static str,
    /// „Egal": no choice made.
    pub any: &'static str,
    pub years_only: &'static str,
    pub years: &'static str,
    pub even: &'static str,
    pub odd: &'static str,
    pub location: &'static str,
    pub location_hint: &'static str,
    pub show_not_offered: &'static str,
    pub apply: &'static str,
    /// „17 Module anzeigen": the button that closes the phone's sheet; the values are the number
    /// and the number written.
    pub show: fn(u64, &str) -> String,
    /// A chip: excluded, for screen readers („Vorlesung: ausgeschlossen") …
    pub excluded: fn(&str) -> String,
    /// … and what a click does, as its tooltip, while it is off, on, and excluding.
    pub chip_off: &'static str,
    pub chip_with: &'static str,
    pub chip_without: &'static str,
    /// The credit slider: all credits, its name, its ends and the fields beside it.
    pub credits_all: &'static str,
    pub credit_points: &'static str,
    pub credits_min: &'static str,
    pub credits_max: &'static str,
    pub from: &'static str,
    pub to: &'static str,
}

