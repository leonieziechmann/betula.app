//! Texts of a Termin's own view (`termin.rs`, folia/design/termin). What QIS says stays as QIS says
//! it: the event's type and title, rooms, people, groups, the reason of a cancelled date and the
//! notes of a room.

use folia_calendar::kind::EventKind;

pub struct Texts {
    /// The view's name for screen readers: „Termin".
    pub panel: &'static str,
    /// The tooltip of „Schließen".
    pub close_title: &'static str,
    /// „Teilen" and its tooltip: the link to the Termin's own page (`/event/<key>/<day>`), to the
    /// device's share sheet on a touch screen, else copied.
    pub share: &'static str,
    pub share_title: &'static str,
    /// „Ganze Seite" (V) and its tooltip: the Termin filling the page it stood beside.
    pub full: &'static str,
    pub full_title: &'static str,
    /// The arrows beside the date: „Voriger Termin", „Nächster Termin".
    pub earlier: &'static str,
    pub later: &'static str,
    /// The week of a Termin held every other week, for screen readers: „A-Woche", „B-Woche".
    pub week_of: fn(&str) -> String,
    /// Where the date stands, beside it: „Fällt aus", „ausgeblendet", „läuft · noch 20 min" …
    pub cancelled: &'static str,
    pub hidden: &'static str,
    pub running: fn(&str) -> String,
    /// … „vorbei", „heute", „in 40 min", „morgen", „übermorgen", „in 5 Tagen", „vor 3 Tagen".
    pub past: &'static str,
    pub in_time: fn(&str) -> String,
    pub tomorrow: &'static str,
    pub day_after: &'static str,
    pub in_days: fn(i32) -> String,
    /// A span of minutes: „40 min", „2 h", „2 h 10 min".
    pub minutes: fn(u16) -> String,
    /// Under the start: „bis 10:45"; a Termin without a clear time: „Zeit unklar".
    pub until: fn(&str) -> String,
    pub no_time: &'static str,
    /// A Termin whose room QIS does not name: „Raum nicht angegeben".
    pub no_room: &'static str,
    /// Who leads the Termin, under the name, by its kind: „hält die Vorlesung", „leitet die Übung"
    /// …; the module's responsible where the Termin names nobody: „verantwortet das Modul".
    pub leads: fn(Option<EventKind>) -> &'static str,
    pub responsible: &'static str,
    /// The lines under the people: „Überschneidet sich mit VL EvS, 09:15–10:45", „Verlegt auf
    /// 12.11.", why the plan leaves the Termin out („Ausgeblendet", „Andere Gruppe gewählt",
    /// „Andere Option gewählt", „„Übung“ ausgeblendet", „Anderer Standort", „Für andere
    /// Studiengänge").
    pub meets: fn(&str) -> String,
    pub moved_to: fn(&str) -> String,
    pub hidden_event: &'static str,
    pub other_group: &'static str,
    pub other_option: &'static str,
    pub kind_off: fn(&str) -> String,
    pub other_place: &'static str,
    pub other_programs: &'static str,
    /// The section that changes the plan: „Im Stundenplan", and what it changes besides: „auch im
    /// Kalender-Abo".
    pub in_plan: &'static str,
    pub in_feed: &'static str,
    /// The groups of a choice: their word by the event's kind („Übungsgruppen" …, else
    /// „Gruppen"), how many are ticked („2 von 7") or „noch keine", and while none is: „Bis du
    /// eine anhakst, stehen alle 4 gestrichelt im Stundenplan."
    pub groups: fn(Option<EventKind>) -> &'static str,
    pub ticked_of: fn(usize, usize) -> String,
    pub none_yet: &'static str,
    pub open_note: fn(usize) -> String,
    /// To look up: „eine von 7".
    pub one_of: fn(usize) -> String,
    /// The tile that folds the rest of a long grid out („+2", „weitere") and in again
    /// („weniger").
    pub further: &'static str,
    pub fewer: &'static str,
    pub more_label: fn(usize) -> String,
    /// What a tile says to screen readers after its time and room: „, passt", „, überschneidet
    /// sich mit VL EvS", „, in deinem Stundenplan".
    pub fits_said: &'static str,
    pub meets_said: fn(&str) -> String,
    pub ticked_said: &'static str,
    /// The event's switch: „Übung zeigen", and when: „an allen Tagen", „mit den angehakten
    /// Gruppen", „an keinem Tag".
    pub show_kind: fn(&str) -> String,
    pub every_day: &'static str,
    pub with_ticked: &'static str,
    pub no_day: &'static str,
    /// One date: „Nur am Mi 04.11.", „die anderen Termine bleiben", „ausgeblendet, die anderen
    /// Termine bleiben", „Ausblenden", „Zeigen".
    pub only_on: fn(&str) -> String,
    pub others_stay: &'static str,
    pub hidden_others_stay: &'static str,
    pub hide: &'static str,
    pub show: &'static str,
    /// „Der Tag" with the plan's Termine; after this one: „danach 11:30 Ü EvS · VG1C/0.03" and the
    /// time between („20 min Pause", a walk where the building changes), or „danach frei".
    pub the_day: &'static str,
    pub then: &'static str,
    pub then_free: &'static str,
    pub pause: fn(&str) -> String,
    /// „Reihe": „6 von 15 · noch 9", „15 Termine · noch 9".
    pub series: &'static str,
    pub nth_of: fn(usize, usize) -> String,
    pub dates: fn(usize) -> String,
    pub left: fn(usize) -> String,
    /// What a dot of the series says: „vorbei", „fällt aus", „ausgeblendet", and a room note.
    pub dot_past: &'static str,
    /// „Zeitraum und Ausnahmen": „wöchentlich, Di 09:15–10:45, 06.10.–26.01. · 15 Termine", the
    /// rhythms („wöchentlich", „14-täglich, A-Woche", „14-täglich, B-Woche", „alle 3 Wochen",
    /// „alle 4 Wochen", „einzeln", „als Block"), „keine Ausnahmen", that the period is assumed,
    /// and a date cancelled: „fällt aus".
    pub range: &'static str,
    pub weekly: &'static str,
    pub fortnightly: fn(&str) -> String,
    pub every_weeks: fn(u8) -> String,
    pub single: &'static str,
    pub block: &'static str,
    pub no_exceptions: &'static str,
    pub assumed: &'static str,
    pub falls_out: &'static str,
    /// What picks the Termin, under the head: the module's events, for screen readers
    /// („Veranstaltungen des Moduls"); the Termine of an event held at several times without groups
    /// („Termine", „beide", „alle 3").
    pub events: &'static str,
    pub slots: &'static str,
    pub all_held: fn(usize) -> String,
    /// „Modul": „Zum Modul", and its exam: „Prüfung", „in 23 Tagen", „heute", „vorbei".
    pub module: &'static str,
    pub to_module: &'static str,
    pub exam: &'static str,
    pub today: &'static str,
    /// „Lehrende", „laut QIS".
    pub staff: &'static str,
    pub per_qis: &'static str,
    /// The source at the end: „Quelle: QIS", „In QIS öffnen".
    pub source: &'static str,
    pub open_in_qis: &'static str,
    /// A Termin the plan has not (any more): „Diesen Termin hat dein Stundenplan nicht (mehr)."
    pub gone: &'static str,
    /// To look up: the head's tag of a module outside the plan („nicht im Plan"); of one in it,
    /// under the ticket, how many of the event's groups the plan holds („Noch keine in deinem
    /// Stundenplan", „Eine in deinem Stundenplan", „2 in deinem Stundenplan"; of an event without
    /// groups „Im Stundenplan") and the way into the Stundenplan („Anpassen").
    pub not_in_plan: &'static str,
    pub in_your_plan: fn(usize) -> String,
    pub adjust: &'static str,
    /// The Termin's dates as a file for one's calendar, of a module outside the plan: „In den
    /// Kalender", its tooltip, and the file's name.
    pub into_calendar: &'static str,
    pub into_calendar_title: &'static str,
    pub calendar_file: fn(&str) -> String,
    /// A Termin of one's own (folia/design/kalender/termine.html): the head's chip and the name of
    /// one without a name („Eigener Termin"), its section („Im Stundenplan", „nicht in Datei und
    /// Abo" until „Eigene Termine mitnehmen"), how it recurs („Jede Woche", „A-Woche", „B-Woche",
    /// „An 3 Tagen", „Einmal") and when („05.10.–31.01., die Vorlesungszeit", „ab 15.10."),
    /// „Bearbeiten", „Löschen" with „mit „Rückgängig“", the way to it from the start page
    /// („Im Stundenplan ändern"), and the source at the end („Von dir angelegt", where one of QIS
    /// says „Quelle: QIS").
    pub own_chip: &'static str,
    pub own_feed: &'static str,
    pub own_week: &'static str,
    pub own_a_week: &'static str,
    pub own_b_week: &'static str,
    pub own_dates: fn(usize) -> String,
    pub own_lectures: fn(&str) -> String,
    pub own_from: fn(&str) -> String,
    pub own_until: fn(&str) -> String,
    pub own_edit: &'static str,
    pub own_edit_title: &'static str,
    pub own_remove: &'static str,
    pub own_remove_sub: &'static str,
    pub own_change: &'static str,
    pub own_source: &'static str,
    /// A Termin's own page (`/event/<key>/<day>`): its title in the browser's tab and for link
    /// previews („Übung · Mathematik IT-1 · Di 04.11."), what it says of itself („Übung
    /// Mathematik IT-1 am Di 04.11. um 09:15, LG1A/304: die Termine der Reihe, laut QIS."), and
    /// a Termin that does not exist.
    pub page_title: fn(&str, &str, &str) -> String,
    pub page_description: fn(&str, &str) -> String,
    pub not_found: &'static str,
    pub not_found_hint: &'static str,
}

