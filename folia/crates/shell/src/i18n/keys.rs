//! Texts of the overview of the keys (`crate::keys`): its head, its groups and their rows. A row is
//! the keys (specs of `folia_design::keys`, several are alternatives; `Nav` is the navigation's
//! keys and a digit, as the system has them) and what they do.

/// A row of the overview: its keys and its words.
pub type Row = (&'static [&'static str], &'static str);

pub struct Texts {
    pub title: &'static str,
    pub lead: &'static str,
    /// The button in the rail that opens it: its name, and its tooltip with its key.
    pub button: &'static str,
    pub button_title: &'static str,
    /// Its command in „Befehle" (`crate::commands`).
    pub all: &'static str,
    /// The mark at the group of where the keyboard was.
    pub here: &'static str,
    pub everywhere: &'static str,
    pub everywhere_rows: &'static [Row],
    pub list: &'static str,
    pub list_rows: &'static [Row],
    pub filters: &'static str,
    pub filters_rows: &'static [Row],
    pub module: &'static str,
    pub module_rows: &'static [Row],
    /// A Termin in its own view (folia/crates/widgets/src/termin.rs).
    pub termin: &'static str,
    pub termin_rows: &'static [Row],
    /// The Merkliste's list and its sidebar (the collections and the filters).
    pub marked: &'static str,
    pub marked_rows: &'static [Row],
    pub sidebar: &'static str,
    pub sidebar_rows: &'static [Row],
    /// „Mein Studium": a semester and its rows, the sidebar of the views, the Gesamtplan.
    pub study: &'static str,
    pub study_rows: &'static [Row],
    pub study_side: &'static str,
    pub study_side_rows: &'static [Row],
    pub grid: &'static str,
    pub grid_rows: &'static [Row],
    /// The Stundenplan: its week and its modules, and its sidebar (the calendars, the export,
    /// „Teilen …").
    pub plan: &'static str,
    pub plan_rows: &'static [Row],
    pub plan_side: &'static str,
    pub plan_side_rows: &'static [Row],
}

