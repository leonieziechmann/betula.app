//! Texts of the frame of every page: the rail, the top bar with its search, the bottom bar of a
//! phone (`lib.rs`).

pub struct Texts {
    /// The title of a page that sets none (the start page names itself).
    pub default_title: &'static str,
    pub skip_to_content: &'static str,
    pub not_found_title: &'static str,
    pub not_found_hint: &'static str,
    /// The names of the navigations, for screen readers.
    pub navigation: &'static str,
    pub main_navigation: &'static str,
    /// The areas, as the rail and the bottom bar name them.
    pub home: &'static str,
    pub modules: &'static str,
    pub programs: &'static str,
    /// The programs' tab in the rail, where „Studiengänge" is too long.
    pub study: &'static str,
    /// „Mein Studium": the title of the Studium tab's first page in the top bar.
    pub my_studies: &'static str,
    pub bookmarks: &'static str,
    pub studyplan: &'static str,
    /// The number on the tab of the Merkliste and the Stundenplan: „3 gemerkt", „5 geplant".
    pub marked_count: fn(usize) -> String,
    pub planned_count: fn(usize) -> String,
    pub logo_label: &'static str,
    pub theme_toggle: &'static str,
    /// The profile page („Profil"): its title in the top bar, and the way to it in the rail and at
    /// the head of a phone's page, named by the active profile („Profil: Zweitstudium").
    pub profile: &'static str,
    pub profile_of: fn(&str) -> String,
    /// The menu of the profiles at the way to the profile page (`chrome::ProfileMenu`): its name,
    /// the head of its list, and its way to the profile page.
    pub switch_profile: &'static str,
    pub profiles: &'static str,
    pub profile_and_settings: &'static str,
    /// „Neues Profil" in the menu of the profiles: the way, its field's name, its button, and why
    /// there can be no other (as the profile page says them, `folia_profile`).
    pub new_profile: &'static str,
    pub new_profile_name: &'static str,
    pub create_profile: &'static str,
    pub profiles_full: fn(usize) -> String,
    pub search_programs: &'static str,
    pub search_programs_placeholder: &'static str,
    pub search_modules: &'static str,
    pub search_modules_placeholder: &'static str,
    /// The search at the head on the Merkliste: its name, and what it says while empty.
    pub search_bookmarks: &'static str,
    pub search_bookmarks_placeholder: &'static str,
    /// What the tab of „Studium" holds besides its page (a long press, a right click): the
    /// menu's name, and its ways.
    pub shortcuts: fn(&str) -> String,
    pub to_plan: &'static str,
    pub to_areas: &'static str,
    pub all_programs: &'static str,
    /// The Merkliste's tab, held (folia/design/merken/oberflaeche.html, „Der Tab, lange
    /// gedrückt"): the whole list and „Ohne Sammlung" before the collections.
    pub all_marked: &'static str,
    pub without_collection: &'static str,
}

