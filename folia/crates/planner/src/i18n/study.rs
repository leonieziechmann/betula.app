//! Texts of „Mein Studium" (`study/`): the Studium tab's page, the study planned semester by
//! semester.

pub struct Texts {
    /// The page's title and the sidebar's heading.
    pub title: &'static str,
    /// What the server writes in the page's place (the page is the app's): its title and hint.
    pub server_title: &'static str,
    pub server_hint: &'static str,
    /// The description of the page for link previews.
    pub seo_description: &'static str,

    // The first visit.
    /// „Richte dein Studium einmal ein" and the lead under it.
    pub setup_title: &'static str,
    pub setup_lead: &'static str,
    /// The program kept is in the catalog no longer (its stored name).
    pub gone: fn(&str) -> String,
    /// „Studiengang", „Studienbeginn", „Studienrichtung": the fields' labels.
    pub program: &'static str,
    pub start: &'static str,
    pub direction: &'static str,
    pub choose_program: &'static str,
    pub search_program: &'static str,
    /// A program of one plan: what its study direction's field says.
    pub no_direction: &'static str,
    /// „WiSe 2025/26 · jetzt 3. FS": a Studienbeginn and the Fachsemester it makes the current one.
    pub start_entry: fn(&str, u8) -> String,
    /// „Deine bisherigen Semester": how the semesters before the current one begin.
    pub past_legend: &'static str,
    pub start_empty: &'static str,
    pub start_empty_hint: &'static str,
    /// „1. und 2. FS nach Regelstudienplan füllen" (the span written already) and its hint.
    pub fill_past: fn(&str) -> String,
    pub fill_past_hint: &'static str,
    /// „Studium anlegen".
    pub create: &'static str,
    /// „Bleibt in diesem Browser."
    pub stays_here: &'static str,
    /// „Alle Studiengänge ansehen": the way to the overview.
    pub all_programs: &'static str,

    // The sidebar.
    /// „Studiengang ändern …": the program's card opens „Studiengang wechseln".
    pub change_program: &'static str,
    /// „Beginnt im WiSe 2026/27": the card of a study that has not begun yet.
    pub begins_in: fn(&str) -> String,
    /// The ways to the program's pages.
    pub ways: &'static str,
    pub to_plan: &'static str,
    pub to_areas: &'static str,
    /// The legend: the parts of the bar („Fortschrittsbalken"), then the marks of a module
    /// („Zeichen an Modulen"), each a word.
    pub legend_bar: &'static str,
    pub legend_marks: &'static str,
    pub legend_passed: &'static str,
    pub legend_planned: &'static str,
    pub legend_open: &'static str,
    pub legend_over: &'static str,
    pub legend_retake: &'static str,
    pub legend_offer: &'static str,
    /// Where all of it lives.
    pub storage_hint: &'static str,

    // „Studiengang wechseln".
    pub switch_title: &'static str,
    pub switch_lead: &'static str,
    /// „Bisher" and „seit WiSe 2025/26".
    pub switch_before: &'static str,
    pub since: fn(&str) -> String,
    pub new_program: &'static str,
    /// „So zählt dein Plan in Wirtschaftsinformatik".
    pub counts_title: fn(&str) -> String,
    pub counts_passed: &'static str,
    pub counts_planned: &'static str,
    /// „von 46 LP" … „kommen dort vor".
    pub of_credits: fn(&str) -> String,
    pub counts_there: &'static str,
    /// The modules that count for nothing there.
    pub not_there: &'static str,
    pub passed_word: &'static str,
    pub planned_word: &'static str,
    pub nothing_lost: &'static str,
    pub cancel: &'static str,
    /// „Zu Wirtschaftsinformatik wechseln"; „Übernehmen" where the program stays.
    pub switch_to: fn(&str) -> String,
    pub apply: &'static str,

    // The overview.
    /// „Übersicht · Informatik B.Sc." over the headline.
    pub overview: &'static str,
    /// „46 von 180 LP bestanden"; without a plan „46 LP bestanden".
    pub headline: fn(&str, &str) -> String,
    pub headline_alone: fn(&str) -> String,
    /// „46 LP" … „bestanden", „geplant, davon 6 über Bedarf", „noch nicht eingeplant".
    pub credits: fn(&str) -> String,
    pub passed_tail: &'static str,
    pub planned_tail: &'static str,
    pub over_part: fn(&str) -> String,
    pub outside_part: fn(&str) -> String,
    pub open_tail: &'static str,
    /// On a phone: „46 bestanden · 50 geplant · 90 offen".
    pub passed_short: &'static str,
    pub planned_short: &'static str,
    pub open_short: &'static str,
    /// The bar, for screen readers, and one area of it.
    pub bar_label: &'static str,
    pub bar_area: fn(&str, &str, &str, &str) -> String,
    /// „Bereiche": the way to the areas on a phone.
    pub areas: &'static str,

    // A phone: the overview, then the semesters behind „Studium planen".
    /// „Studium planen": the box that leads to the semesters, and their page.
    pub plan_box: &'static str,
    /// „Jetzt WiSe 2026/27 · 8 von 32 LP": the box's line of the current semester.
    pub box_now: fn(&str, &str) -> String,
    /// The box's columns, for screen readers: „Deine Semester".
    pub chart_label: &'static str,
    /// Under a semester of leave's column: „Urlaub".
    pub leave_short: &'static str,
    /// What an area's card says: „32 bestanden · 16 geplant", „noch nichts geplant", „18 LP
    /// offen", „ganz eingeplant", „+6 LP über Bedarf", „laut Plan im 5.–6. FS".
    pub card_passed: fn(&str) -> String,
    pub card_planned: fn(&str) -> String,
    pub nothing_yet: &'static str,
    pub card_open: fn(&str) -> String,
    pub all_planned: &'static str,
    pub card_over: fn(&str) -> String,
    /// An area's card on a desktop, in one line („Informatik 44/66"), says the rest when the
    /// pointer rests on it: „Informatik: 44 von 66 LP belegt, 22 LP offen".
    pub card_title: fn(&str, &str, &str, &str) -> String,
    pub plan_says: fn(&str) -> String,
    /// The areas the page names itself.
    pub fues: &'static str,
    pub fues_full: &'static str,
    pub thesis: &'static str,
    pub other: &'static str,
    pub outside: &'static str,
    /// „Einplanen": a Wiederholer not planned again, into the next semester that offers it.
    pub plan_it: &'static str,

    // An area.
    /// „Übersicht nach Bereichen": the phone's sheet.
    pub areas_title: &'static str,
    /// „Verlangt 6 LP · belegt 12 LP", „verlangt: 6 LP".
    pub area_asks: fn(&str, &str) -> String,
    pub area_required: fn(&str) -> String,
    pub area_over_text: fn(&str) -> String,
    pub your_modules: &'static str,
    pub none_here: &'static str,
    /// „bestanden im WiSe 2025/26", „geplant im SoSe 2027", „nicht bestanden im SoSe 2026".
    pub passed_in: fn(&str) -> String,
    pub planned_in: fn(&str) -> String,
    pub failed_in: fn(&str) -> String,
    pub over_need: &'static str,
    /// „Laut Regelstudienplan": the area's rows and where each stands.
    pub plan_rows: &'static str,
    pub row_open: &'static str,
    pub more_area: &'static str,
    pub area_catalog: &'static str,
    pub fues_catalog: &'static str,
    pub area_rules: &'static str,
    pub close: &'static str,

    // The semesters.
    pub semesters: &'static str,
    pub choose_semester: &'static str,
    pub previous: &'static str,
    pub next: &'static str,
    pub now: &'static str,
    pub leave: &'static str,
    pub beyond: &'static str,
    /// „3. FS", „3. Fachsemester".
    pub fs: fn(u8) -> String,
    pub fs_long: fn(u8) -> String,
    /// „1. FS", „1. und 2. FS", „1.–4. FS".
    pub fs_span: fn(u8, u8) -> String,
    /// The strip: „von 32 bestanden", „von 30 LP", „noch leer", „Plan 30".
    pub of_passed: fn(&str) -> String,
    pub of_planned: fn(&str) -> String,
    pub still_empty: &'static str,
    pub plan_n: fn(&str) -> String,
    /// The head of a semester: „8 mehr", „24 von 32 LP bestanden".
    pub more: fn(&str) -> String,
    pub head_past: fn(&str, &str) -> String,
    /// „Semester anfügen".
    pub add_semester: &'static str,
    /// The columns of a semester.
    pub col_module: &'static str,
    pub col_area: &'static str,
    pub col_credits: &'static str,
    /// A row's ⋯ and a semester's, for screen readers: „Mehr zu Datenbanken".
    pub more_about: fn(&str) -> String,
    /// The marks of a row: „Wiederholung · aus 1. FS", „im SoSe nicht angeboten", „nur WiSe" …
    pub chip_retake: fn(&str) -> String,
    pub unoffered: fn(&str) -> String,
    pub only_winter: &'static str,
    pub only_summer: &'static str,
    /// … „über Bedarf · FÜS hat schon 6 LP" …
    pub over_full: fn(&str, &str) -> String,
    /// … „nicht bestanden · wieder im WiSe 2026/27", „… noch nicht wieder eingeplant" …
    pub failed_again: fn(&str) -> String,
    pub failed_open: &'static str,
    /// … „Platzhalter", „gefüllt mit Datenbanken" …
    pub placeholder: &'static str,
    pub filled_with: fn(&str) -> String,
    pub no_area: &'static str,
    /// „Module hinzufügen", „Im Stundenplan öffnen".
    pub add_modules: &'static str,
    pub in_timetable: &'static str,
    pub empty_semester: &'static str,
    pub empty_leave: &'static str,
    /// „Im 4. FS sieht der Regelstudienplan noch vor: …".
    pub plan_still: fn(&str, &str) -> String,
    /// „Als Urlaubssemester" and what it means; „Semester entfernen".
    pub as_leave: &'static str,
    pub leave_note: &'static str,
    pub remove_semester: &'static str,

    // „Passt in dieses Semester".
    pub fits_title: &'static str,
    pub fits_plan: fn(&str) -> String,
    pub fits_all: &'static str,
    pub fits_nothing: &'static str,
    /// „Was noch offen ist, wird im SoSe nicht angeboten.": the plan's rows of the Fachsemester
    /// left open are all of the other half of the year.
    pub fits_unoffered: fn(&str) -> String,
    pub retakes: &'static str,
    /// „Aus früheren Fachsemestern": the plan's rows of the Fachsemester before, still open.
    pub fits_earlier: &'static str,
    pub search_catalog: &'static str,
    pub plan_here: fn(&str) -> String,
    pub from_fs: fn(&str) -> String,

    // A semester more.
    pub new_semester: &'static str,
    pub after: fn(&str) -> String,
    pub append_title: &'static str,
    pub append_lead: fn(u8) -> String,
    pub append_lead_plain: &'static str,
    pub append: fn(&str) -> String,

    // „Module hinzufügen".
    pub add_title: &'static str,
    /// „SoSe 2027 · 4. Fachsemester · bisher 12 LP".
    pub add_sub: fn(&str, &str, &str) -> String,
    pub tab_plan: &'static str,
    pub tab_catalog: &'static str,
    pub plan_semester: &'static str,
    pub plan_fs_heading: fn(&str) -> String,
    pub select: fn(&str) -> String,
    pub move_here: fn(&str) -> String,
    pub placeholder_note: &'static str,
    pub choose_module: &'static str,
    /// „schon geplant im WiSe 2026/27", „ – würde hierher verschoben", „hier geplant".
    pub already_planned: fn(&str) -> String,
    pub would_move: &'static str,
    pub planned_here: &'static str,
    /// „jedes SoSe", „jedes Semester".
    pub every: fn(&str) -> String,
    pub every_semester: &'static str,
    /// „früher nicht bestanden".
    pub retakes_sub: &'static str,
    /// „3 ausgewählt · 18 LP".
    pub selected: fn(usize, &str) -> String,
    /// „SoSe 2027 danach: 30 LP – so viel wie im Regelstudienplan" and the other two.
    pub after_add: fn(&str, &str) -> String,
    pub as_planned: &'static str,
    pub more_than_plan: fn(&str) -> String,
    pub less_than_plan: fn(&str) -> String,
    pub insert: fn(usize) -> String,
    pub search_placeholder: &'static str,
    pub only_program: &'static str,
    pub no_hits: &'static str,
    pub type_to_search: &'static str,
    /// The cell of the Gesamtplan: „Fachstudium · WiSe 2027/28", „Offen: 44 LP", „Alle".
    pub cell_open: fn(&str) -> String,
    pub all: &'static str,
    pub not_offered_group: fn(&str, usize) -> String,

    // What a module asks for.
    /// „empfiehlt", „setzt voraus" before the list.
    pub recommends: fn(&str) -> String,
    pub requires: fn(&str) -> String,
    /// „MIT2 ✓", „im WiSe 26/27", „im selben Semester", „erst im SoSe 2028", „noch nicht
    /// eingeplant".
    pub need_before: fn(&str) -> String,
    pub need_same: &'static str,
    pub need_after: fn(&str) -> String,
    pub need_open: &'static str,

    // A row's menu, and the bar of the rows selected.
    pub view_module: &'static str,
    /// „Als bestanden markieren", and taking that back.
    pub mark_passed: &'static str,
    pub unmark_passed: &'static str,
    /// „Verschieben nach ›"; the submenu's title on a phone: „„Datenbanken“ verschieben nach",
    /// „3 Einträge verschieben nach".
    pub move_to: &'static str,
    pub move_title: fn(&str) -> String,
    pub move_n: fn(usize) -> String,
    /// Where it moves to: „angeboten", „nicht angeboten", „2 nicht angeboten".
    pub offered: &'static str,
    pub not_offered: &'static str,
    pub n_not_offered: fn(usize) -> String,
    pub remove: &'static str,
    /// The box of a row and the one of all, for screen readers; the bar: „Auswahl", „Auswahl
    /// aufheben", „3 Einträge" (what a drag of several shows); on a phone its words are short.
    pub select_all: &'static str,
    pub n_selected: fn(usize) -> String,
    pub selection: &'static str,
    pub clear_selection: &'static str,
    pub n_entries: fn(usize) -> String,
    pub act_passed: &'static str,
    pub unmark_short: &'static str,
    pub act_move: &'static str,
    /// The notes with „Rückgängig": „„Datenbanken“ entfernt", „… ins SoSe 2027 verschoben",
    /// „3 hinzugefügt", „„Datenbanken“ als bestanden markiert" and the same of several.
    pub removed: fn(&str) -> String,
    pub n_removed: fn(usize) -> String,
    pub moved: fn(&str, &str) -> String,
    pub n_moved: fn(usize, &str) -> String,
    pub added: fn(usize) -> String,
    pub marked_passed: fn(&str) -> String,
    pub n_marked_passed: fn(usize) -> String,
    pub unmarked_passed: fn(&str) -> String,
    pub n_unmarked_passed: fn(usize) -> String,

    // The views.
    pub view_label: &'static str,
    pub view_semester: &'static str,
    pub view_grid: &'static str,

    // The Gesamtplan.
    pub grid_title: &'static str,
    pub so_far: &'static str,
    pub expand_past: &'static str,
    pub collapse_past: &'static str,
    /// „✓ 32 LP · 5 Module".
    pub past_cell: fn(&str, &str) -> String,
    pub grid_grey: &'static str,
    pub grid_help: &'static str,
    pub add_in_cell: &'static str,
    /// The title of a grey line: „laut Regelstudienplan im 4. FS · Klick fügt hinzu", „Wiederholer:
    /// im SoSe 2026 nicht bestanden · Klick fügt hinzu".
    pub line_title: fn(&str) -> String,
    pub line_retake: fn(&str) -> String,
}

