//! Texts of „Notenübersicht einlesen" in „Mein Studium" (`study/transcript.rs`): the way to it,
//! the dialog that says what was read and what it does to the study, and why a file was not read.

pub struct Texts {
    /// The way: „Notenübersicht einlesen", the line under it, the same while the file is read.
    pub way: &'static str,
    pub way_line: &'static str,
    pub reading: &'static str,
    /// The first visit's box: what it does.
    pub setup_title: &'static str,
    pub setup_line: &'static str,

    /// The dialog's title, and the line under it once the file is read.
    pub title: &'static str,
    pub read_here: &'static str,
    /// The program the Notenübersicht names: „seit WiSe 2022/23"; what becomes of it.
    pub since: fn(&str) -> String,
    pub program_same: &'static str,
    pub program_new: &'static str,
    pub program_instead: fn(&str) -> String,
    /// The program the Notenübersicht names is not in the catalog: „„Informatik“ (Bachelor)".
    pub program_missing: fn(&str) -> String,
    /// A name as the Notenübersicht writes it, in quotes.
    pub quoted: fn(&str) -> String,
    /// Without a program kept nor found, nothing can be taken over.
    pub program_needed: &'static str,
    /// „36 Module gelesen", and what they are.
    pub modules_read: fn(usize) -> String,
    pub n_passed: fn(usize) -> String,
    pub n_failed: fn(usize) -> String,
    pub n_registered: fn(usize) -> String,
    /// What taking them over changes: „12 neu", „8 schon so", „3 verschoben".
    pub n_new: fn(usize) -> String,
    pub n_kept: fn(usize) -> String,
    pub n_moved: fn(usize) -> String,
    /// The list of what is taken over, and of what the catalog does not have.
    pub taken: &'static str,
    pub not_found: &'static str,
    pub not_found_hint: &'static str,
    /// What a row says of itself.
    pub change_new: &'static str,
    pub change_kept: &'static str,
    pub change_moved: fn(&str) -> String,
    pub change_removed: fn(&str) -> String,
    pub change_unmarked: &'static str,
    pub change_full: &'static str,
    pub registered_then: fn(&str) -> String,
    pub finally_failed: &'static str,
    pub recognised: &'static str,
    pub no_term: &'static str,
    pub unknown_status: fn(&str) -> String,
    /// Where it was read and what of it stays.
    pub privacy: &'static str,
    pub apply: &'static str,
    pub apply_setup: &'static str,
    pub cancel: &'static str,
    pub close: &'static str,
    /// The note after it was taken over, with „Rückgängig".
    pub done: fn(usize) -> String,

    /// Why a file was not read.
    pub not_pdf: &'static str,
    pub locked: &'static str,
    pub not_transcript: &'static str,
    pub too_large: &'static str,
    pub failed: &'static str,
    pub try_again: &'static str,
}

