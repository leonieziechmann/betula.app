//! Texts of the dialog „Teilen" (`pages/studyplan/share_dialog.rs`; folia/design/teilen/teilen.html):
//! the shares in force, the choices of a new one, the offer of Betula Sync where it makes a choice
//! better, and the link made.

pub struct Texts {
    // ---- the head ----
    /// „Stundenplan teilen", and for a calendar of one's own „Kalender „Lena“ teilen".
    pub title: &'static str,
    pub title_calendar: fn(&str) -> String,
    /// The line under it: the semester and how many modules („WiSe 2026/27 · 6 Module").
    pub sub: fn(&str, usize) -> String,
    /// The entry of the sidebar's group „Plan" that opens it, and the line under it.
    pub open: &'static str,
    pub open_hint: &'static str,

    // ---- the shares in force ----
    pub shared: &'static str,
    /// What a share is, as its row names it.
    pub row_once: &'static str,
    pub row_everyone: &'static str,
    pub row_app: &'static str,
    /// Its state: „aktuell", „fester Stand"; a one-time link „noch nicht geöffnet · bis 15. Nov.".
    pub live: &'static str,
    pub fixed: &'static str,
    pub waiting: fn(&str) -> String,
    pub with_own: &'static str,
    pub since: fn(&str) -> String,
    /// Its buttons.
    pub stop: &'static str,
    pub withdraw: &'static str,
    pub copy_again: &'static str,
    /// A share could not be taken back now.
    pub stop_failed: &'static str,
    /// A share made just now.
    pub new: &'static str,

    // ---- the choices ----
    pub people: &'static str,
    pub app: &'static str,
    pub how: &'static str,
    pub stays: &'static str,
    pub stays_people: &'static str,
    pub stays_app: &'static str,
    pub copy: &'static str,
    pub copy_people: &'static str,
    pub copy_app: &'static str,
    pub who_opens: &'static str,
    pub one: &'static str,
    pub one_hint: &'static str,
    pub everyone: &'static str,
    pub everyone_hint: &'static str,
    /// The mark of a choice that needs Betula Sync, in a private profile.
    pub with_sync: &'static str,

    // ---- what each choice means ----
    pub note_copy_everyone: &'static str,
    pub note_copy_one: &'static str,
    pub note_live_everyone: &'static str,
    pub note_app_live: &'static str,
    pub note_app_copy: &'static str,
    /// Nothing planned: a fixed link needs a module.
    pub note_nothing: &'static str,
    /// The own Termine and notes go along only in a share kept at Phloem.
    pub note_along_fixed: &'static str,

    // ---- Betula Sync ----
    /// A choice that needs it: what saving the profile means.
    pub needs_sync: &'static str,
    pub needs_sync_hint: &'static str,
    /// The offers of what it makes better, and its button.
    pub offer_people: &'static str,
    pub offer_people_hint: &'static str,
    pub offer_app: &'static str,
    pub offer_app_hint: &'static str,
    pub save_profile: &'static str,
    pub saving: &'static str,
    /// Saving the profile did not work.
    pub save_failed: &'static str,

    // ---- what comes along ----
    pub along: &'static str,
    pub always: &'static str,
    pub always_list: &'static str,
    pub own: &'static str,
    pub own_count: fn(usize) -> String,
    pub notes: &'static str,
    pub notes_app: &'static str,
    pub notes_count: fn(usize) -> String,
    pub for_whom: &'static str,
    pub for_whom_placeholder: &'static str,
    pub for_whom_hint: &'static str,

    // ---- the buttons ----
    pub cancel: &'static str,
    pub create_link: &'static str,
    pub create_once: &'static str,
    pub create_address: &'static str,
    pub save_and_link: &'static str,
    pub save_and_address: &'static str,
    pub creating: &'static str,
    pub another: &'static str,
    pub done: &'static str,

    // ---- the link made ----
    pub link: &'static str,
    pub address: &'static str,
    pub qr_label: &'static str,
    pub copy_link: &'static str,
    pub copy_address: &'static str,
    pub copied: &'static str,
    pub share_more: &'static str,
    pub meta_once: fn(&str) -> String,
    pub meta_live: &'static str,
    pub meta_copy: &'static str,
    pub meta_app_live: &'static str,
    pub meta_app_copy: &'static str,
    /// Notes or Termine of one's own that did not fit in the shared calendar.
    pub left_out: fn(usize) -> String,
    /// The line of what it is, its parts joined with „ · ".
    pub summary_live: &'static str,
    pub summary_copy: &'static str,
    pub summary_one: &'static str,
    pub summary_everyone: &'static str,
    pub summary_next: fn(&str) -> String,
    pub summary_own: &'static str,
    pub summary_no_own: &'static str,
    pub summary_notes: &'static str,

    // ---- what went wrong ----
    pub problem_not_synced: &'static str,
    pub problem_too_many: &'static str,
    pub problem_busy: &'static str,
    pub problem_unreachable: &'static str,
    pub problem_unsupported: &'static str,
}

